import { revalidateTag } from "next/cache";
import { after } from "next/server";
import { canUserAddTemplates } from "@/lib/auth/permissions";
import { createSupabaseAuthServerClient } from "@/lib/supabase/server";
import { VIDEO_LINK_ERROR, parseVideoEmbedUrl } from "@/lib/templates/video-embed";
import { slugify } from "@/lib/templates/slug";
import { resolveTemplateSlug } from "@/lib/templates/slug-server";
import { renamePrintableToSlug } from "@/lib/templates/printable-name";
import { parseTemplateSpecs } from "@/lib/templates/specs";
import { parseAffiliateProductIds } from "@/lib/templates/affiliate";
import { parseSimilarTemplateIds } from "@/lib/templates/similar";

type CreateTemplateBody = {
  // Generated by the form, so a retried save (e.g. after a timeout) can't create the template twice.
  id?: unknown;
  title?: unknown;
  slug?: unknown;
  // True when the slug was generated from the title rather than typed by the author.
  slugAuto?: unknown;
  description?: unknown;
  metaTitle?: unknown;
  metaDescription?: unknown;
  categoryIds?: unknown;
  minimumAge?: unknown;
  maximumAge?: unknown;
  durationMinutes?: unknown;
  difficulty?: unknown;
  videoPath?: unknown;
  videoUrl?: unknown;
  thumbnailPath?: unknown;
  printablePath?: unknown;
  isFree?: unknown;
  gender?: unknown;
  galleryPaths?: unknown;
  supplies?: unknown;
  specs?: unknown;
  affiliateProductIds?: unknown;
  similarTemplateIds?: unknown;
  tags?: unknown;
  status?: unknown;
};

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const DIFFICULTIES = new Set(["easy", "medium", "advanced"]);

export async function POST(request: Request) {
  const supabase = await createSupabaseAuthServerClient();
  const { data: { user }, error: authError } = await supabase.auth.getUser();
  if (authError || !user) return Response.json({ error: "Please sign in again." }, { status: 401 });
  if (!canUserAddTemplates(user)) return Response.json({ error: "You do not have permission to add templates." }, { status: 403 });

  let body: CreateTemplateBody;
  try {
    body = await request.json();
  } catch {
    return Response.json({ error: "Invalid request." }, { status: 400 });
  }

  const title = typeof body.title === "string" ? body.title.trim() : "";
  const requestedSlug = typeof body.slug === "string" ? slugify(body.slug.trim()) : "";
  const description = typeof body.description === "string" ? body.description.trim() : "";
  const metaTitle = typeof body.metaTitle === "string" ? body.metaTitle.trim() : "";
  const metaDescription = typeof body.metaDescription === "string" ? body.metaDescription.trim() : "";
  const categoryIds = Array.isArray(body.categoryIds)
    ? [...new Set(body.categoryIds.filter((id): id is string => typeof id === "string"))].slice(0, 20)
    : [];
  const minimumAge = Number(body.minimumAge);
  const maximumAge = Number(body.maximumAge);
  const durationMinutes = Number(body.durationMinutes);
  const difficulty = typeof body.difficulty === "string" ? body.difficulty : "";
  const videoPath = typeof body.videoPath === "string" ? body.videoPath : "";
  const videoUrl = typeof body.videoUrl === "string" ? body.videoUrl.trim() : "";
  const thumbnailPath = typeof body.thumbnailPath === "string" ? body.thumbnailPath : "";
  const printablePath = typeof body.printablePath === "string" ? body.printablePath : "";
  const isFree = body.isFree === true;
  const gender = body.gender === "boy" || body.gender === "girl" ? body.gender : null;
  const status = body.status === "draft" ? "draft" : "published";
  const galleryPaths = Array.isArray(body.galleryPaths) ? body.galleryPaths.filter((path): path is string => typeof path === "string").slice(0, 30) : [];
  const supplies = Array.isArray(body.supplies)
    ? [...new Set(body.supplies.filter((item): item is string => typeof item === "string").map((item) => item.trim()).filter(Boolean))].slice(0, 20)
    : [];
  const specs = parseTemplateSpecs(body.specs);
  const affiliateProductIds = parseAffiliateProductIds(body.affiliateProductIds);
  const similarTemplateIds = parseSimilarTemplateIds(body.similarTemplateIds);
  const tags = Array.isArray(body.tags)
    ? [...new Set(body.tags.filter((item): item is string => typeof item === "string").map((item) => item.trim().toLowerCase()).filter(Boolean))].slice(0, 20)
    : [];
  const dropboxOwnedPrefix = `/lvo-files/${user.id}/`;
  const mediaOwnedPrefix = `${user.id}/`;

  if (!title || title.length > 120) return Response.json({ error: "Add a title under 120 characters." }, { status: 400 });
  if (typeof body.slug === "string" && body.slug.trim() && !requestedSlug) return Response.json({ error: "Enter a slug with letters or numbers." }, { status: 400 });
  if (description.length > 400) return Response.json({ error: "Keep the description under 400 characters." }, { status: 400 });
  if (metaTitle.length > 70) return Response.json({ error: "Keep the meta title under 70 characters." }, { status: 400 });
  if (metaDescription.length > 180) return Response.json({ error: "Keep the meta description under 180 characters." }, { status: 400 });
  if (!categoryIds.length || categoryIds.some((id) => !UUID_PATTERN.test(id))) return Response.json({ error: "Choose at least one category." }, { status: 400 });
  if (!Number.isInteger(minimumAge) || !Number.isInteger(maximumAge) || minimumAge < 0 || maximumAge > 16 || minimumAge > maximumAge) {
    return Response.json({ error: "Enter a valid age range from 0 to 16." }, { status: 400 });
  }
  if (!Number.isInteger(durationMinutes) || durationMinutes < 1 || durationMinutes > 1440) return Response.json({ error: "Enter a valid duration." }, { status: 400 });
  if (!DIFFICULTIES.has(difficulty)) return Response.json({ error: "Choose a difficulty." }, { status: 400 });
  if (videoPath && videoUrl) return Response.json({ error: "Provide either a video upload or a video link, not both." }, { status: 400 });
  if (!videoPath && !videoUrl && !thumbnailPath && !galleryPaths.length) return Response.json({ error: "Add a template video or a featured image." }, { status: 400 });
  if (videoPath && !videoPath.startsWith(dropboxOwnedPrefix)) return Response.json({ error: "Upload a video." }, { status: 400 });
  if (videoUrl && !parseVideoEmbedUrl(videoUrl)) return Response.json({ error: VIDEO_LINK_ERROR }, { status: 400 });
  if (thumbnailPath && !thumbnailPath.startsWith(mediaOwnedPrefix)) return Response.json({ error: "Upload a featured image." }, { status: 400 });
  if (!printablePath.startsWith(dropboxOwnedPrefix)) return Response.json({ error: "Upload a printable PDF." }, { status: 400 });
  if (galleryPaths.some((path) => !path.startsWith(mediaOwnedPrefix))) return Response.json({ error: "Invalid gallery file." }, { status: 400 });

  const templateId = typeof body.id === "string" && UUID_PATTERN.test(body.id) ? body.id.toLowerCase() : crypto.randomUUID();
  // A slug the author typed is used exactly (and rejected if taken, with a suggestion).
  // A generated one quietly becomes slug-2, slug-3, … when it's already used.
  const baseSlug = requestedSlug || slugify(title) || `template-${templateId.slice(0, 8)}`;
  const slugIsAuto = body.slugAuto === true || !requestedSlug;

  // Independent checks run together to keep saving fast.
  const [categoriesResult, slugResult, existingResult] = await Promise.all([
    supabase.from("template_categories").select("id").in("id", categoryIds).eq("is_active", true),
    resolveTemplateSlug(baseSlug).then((value) => ({ value, error: null }), (error: unknown) => ({ value: null, error })),
    supabase.from("templates").select("id, slug, status, created_by").eq("id", templateId).maybeSingle(),
  ]);

  // Already saved by an earlier attempt of this same submission: report that success again.
  if (existingResult.data) {
    if (existingResult.data.created_by !== user.id) return Response.json({ error: "Invalid template." }, { status: 400 });
    return Response.json({ id: existingResult.data.id, slug: existingResult.data.slug, status: existingResult.data.status }, { status: 200 });
  }
  if (categoriesResult.error || (categoriesResult.data ?? []).length !== categoryIds.length) {
    return Response.json({ error: "Choose valid categories." }, { status: 400 });
  }
  const slugCheck = slugResult.value;
  if (!slugCheck) {
    const reason = slugResult.error instanceof Error ? slugResult.error.message : "Unable to check the slug.";
    return Response.json({ error: reason }, { status: 500 });
  }
  if (!slugCheck.available && !slugIsAuto) {
    return Response.json({ error: "That slug is already used by another template.", suggestion: slugCheck.suggestion }, { status: 409 });
  }
  let slug = slugCheck.suggestion;
  const publishedAt = status === "published" ? new Date().toISOString() : null;
  let insertError: { code?: string; message: string } | null = null;

  for (let attempt = 0; attempt < 3; attempt += 1) {
    const result = await supabase.from("templates").insert({
      id: templateId,
      slug,
      title,
      short_description: description,
      meta_title: metaTitle || null,
      meta_description: metaDescription || null,
      duration_minutes: durationMinutes,
      difficulty,
      minimum_age: minimumAge,
      maximum_age: maximumAge,
      video_path: videoPath || null,
      video_embed_url: videoUrl || null,
      printable_path: printablePath,
      is_free: isFree,
      gender,
      thumbnail_path: thumbnailPath || galleryPaths[0] || null,
      status,
      published_at: publishedAt,
      created_by: user.id,
    });
    insertError = result.error;
    if (!insertError) break;
    // Same submission arrived twice at once: the other request created it, so this one succeeds too.
    if (insertError.code === "23505" && /templates_pkey/.test(insertError.message)) {
      const { data: created } = await supabase.from("templates").select("id, slug, status").eq("id", templateId).maybeSingle();
      return Response.json(created ?? { id: templateId, slug, status }, { status: 200 });
    }
    // Someone took the slug between the check and the insert: pick the next free one.
    if (insertError.code !== "23505" || !slugIsAuto) break;
    slug = (await resolveTemplateSlug(baseSlug).catch(() => ({ suggestion: `${baseSlug}-${templateId.slice(0, 6)}` }))).suggestion;
  }

  if (insertError?.code === "23505") {
    const suggestion = await resolveTemplateSlug(baseSlug).then((result) => result.suggestion).catch(() => undefined);
    return Response.json({ error: "That slug is already used by another template.", suggestion }, { status: 409 });
  }
  if (insertError) return Response.json({ error: insertError.message }, { status: 400 });

  try {
    await Promise.all([
      (async () => {
      const { error: categoryLinksError } = await supabase.from("template_category_assignments").insert(
        categoryIds.map((categoryId, index) => ({
          template_id: templateId,
          category_id: categoryId,
          is_primary: index === 0,
          sort_order: index * 10,
        })),
      );
      if (categoryLinksError) throw categoryLinksError;
      })(),
      (async () => {
      if (galleryPaths.length) {
        const { error } = await supabase.from("template_gallery_images").insert(
          galleryPaths.map((storagePath, index) => ({
            template_id: templateId,
            storage_path: storagePath,
            alt_text: `${title} image ${index + 1}`,
            sort_order: (index + 1) * 10,
          })),
        );
        if (error) throw error;
      }
      })(),
      (async () => {
      if (supplies.length) {
        // Insert any new supply names (existing ones are skipped), then read back all their ids.
        const { error: upsertError } = await supabase.from("supplies").upsert(supplies.map((name) => ({ name })), { onConflict: "name", ignoreDuplicates: true });
        if (upsertError) throw upsertError;
        const { data: allSupplies, error: suppliesError } = await supabase.from("supplies").select("id, name").in("name", supplies);
        if (suppliesError) throw suppliesError;
        const byName = new Map((allSupplies ?? []).map((item) => [item.name, item.id]));
        const links = supplies.flatMap((name, index) => {
          const supplyId = byName.get(name);
          return supplyId ? [{ template_id: templateId, supply_id: supplyId, sort_order: (index + 1) * 10 }] : [];
        });
        if (links.length) {
          const { error } = await supabase.from("template_supplies").insert(links);
          if (error) throw error;
        }
      }
      })(),
      (async () => {
      if (similarTemplateIds.length) {
        const { error } = await supabase.from("template_similar").insert(
          similarTemplateIds.map((similarId, index) => ({ template_id: templateId, similar_template_id: similarId, sort_order: (index + 1) * 10 })),
        );
        if (error) throw error;
      }
      })(),
      (async () => {
      if (affiliateProductIds.length) {
        const { error } = await supabase.from("template_affiliate_products").insert(
          affiliateProductIds.map((affiliateProductId, index) => ({ template_id: templateId, affiliate_product_id: affiliateProductId, sort_order: (index + 1) * 10 })),
        );
        if (error) throw error;
      }
      })(),
      (async () => {
      if (specs.length) {
        const { error } = await supabase.from("template_specs").insert(
          specs.map((spec, index) => ({ template_id: templateId, label: spec.label, value: spec.value, sort_order: (index + 1) * 10 })),
        );
        if (error) throw error;
      }
      })(),
      (async () => {
      if (tags.length) {
        const tagRows = tags.map((name) => ({ name, slug: slugify(name) })).filter(({ slug }) => slug);
        const { error: tagUpsertError } = await supabase.from("template_tags").upsert(tagRows, { onConflict: "slug", ignoreDuplicates: true });
        if (tagUpsertError) throw tagUpsertError;
        const { data: savedTags, error: tagsError } = await supabase.from("template_tags").select("id, slug").in("slug", tagRows.map(({ slug }) => slug));
        if (tagsError) throw tagsError;
        const { error: tagLinksError } = await supabase.from("template_tag_assignments").insert(
          (savedTags ?? []).map((tag) => ({ template_id: templateId, tag_id: tag.id })),
        );
        if (tagLinksError) throw tagLinksError;
      }
      })(),
    ]);
  } catch (error) {
    await supabase.from("templates").delete().eq("id", templateId);
    return Response.json({ error: error instanceof Error ? error.message : "Could not save template details." }, { status: 400 });
  }

  revalidateTag("templates", { expire: 0 });
  // Name the stored printable after the final slug without making the author wait for Dropbox.
  after(() => renamePrintableToSlug(templateId, printablePath, slug));
  return Response.json({ id: templateId, slug, status }, { status: 201 });
}
